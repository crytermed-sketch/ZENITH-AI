document.querySelectorAll('.pay-btn').forEach(btn => {
    btn.onclick = function() {
        const method = this.getAttribute('data-method');
        showStatus(method);
    };
});

function showStatus(method) {
    const methodsContainer = document.querySelector('.payment-methods');
    methodsContainer.style.display = 'none';
    paymentStatus.style.display = 'block';
    paymentStatus.innerHTML = '<div class="loader">Ładowanie...</div>';

    setTimeout(() => {
        switch(method) {
            case 'paypal': renderPayPal(); break;
            case 'crypto': renderCrypto(); break;
            case 'psc': renderPSC(); break;
        }
    }, 500);
}

